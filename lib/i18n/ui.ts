const DICT: Record<Locale, Record<UiKey, string>> = { zh, en };

export type UiVars = Record<string, string | number>;

/** 取界面文案；vars 用于替换 {name} 之类的占位符 */
export function t(locale: Locale, key: UiKey, vars?: UiVars): string {
  const raw = DICT[locale][key] ?? zh[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

/** 绑定语言的 t()，方便在组件里 `const tr = translator(locale)` */
export function translator(locale: Locale) {
  return (key: UiKey, vars?: UiVars) => t(locale, key, vars);
}
